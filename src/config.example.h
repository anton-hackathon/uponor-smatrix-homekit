// --- Распайка RS485 ---------------------------------------------------------
// Модуль с аппаратным автопереключением направления (выводы DE/RE не нужны).
// Вывод TXD модуля идёт на RX_PIN (вход ESP32), RXD модуля — на TX_PIN.
static const int RS485_RX_PIN = 16;
static const int RS485_TX_PIN = 17;

// --- Имя устройства ---------------------------------------------------------
// DEVICE_HOSTNAME задаёт адрес <hostname>.local в локальной сети.
#define DEVICE_NAME "Uponor Smatrix"
#define DEVICE_HOSTNAME "uponor"

// --- Часовой пояс (строка формата POSIX TZ) ---------------------------------
// Контроллер X-245 своих часов не имеет — время в шину отправляется по NTP.
// Строка задаёт пояс и правила перехода на летнее время.
// Примеры: "CET-1CEST,M3.5.0/2,M10.5.0/3" (Центральная Европа),
//          "GMT0BST,M3.5.0/1,M10.5.0" (Великобритания),
//          "MSK-3" (Москва, без перехода на летнее время).
#define TIMEZONE "CET-1CEST,M3.5.0/2,M10.5.0/3"

// --- Поправка уставки -------------------------------------------------------
// Документированный параметр Uponor «Heating/cooling offset» (по умолчанию 2 °C):
// при переключении в ОХЛАЖДЕНИЕ уставка увеличивается на это значение, поэтому
// показания на экране термостата = значение с шины + поправка. Методика измерения
// описана в README.
//
// На новой системе начните с 0 и сверьте уставку в приложении «Дом» с экраном
// термостата. Подставьте измеренную разницу, только если она есть.
//
// Внимание: по документации в режиме НАГРЕВА знак поправки противоположный
// (уставка уменьшается). В коде поправка пока применяется односторонне и проверена
// только в режиме охлаждения — см. предупреждение в README и NOTES.
static const float UPONOR_TARGET_TEMP_OFFSET = 0.0f;

// --- Одноразовое стирание пары HomeKit --------------------------------------
// true → плата примерно через 15 секунд после подключения к Wi-Fi стирает все
// сохранённые пары контроллеров и снова становится доступной для добавления
// (флаг sf в записи Bonjour меняется на 1).
//
// Зачем нужно: если плата осталась сопряжена с чужим или недоступным домом, а
// доступа по USB нет (плата обычно стоит у контроллера X-245), команду стирания
// через последовательный порт не отправить. Тогда: загрузить прошивку с true,
// дождаться sf=1, загрузить обратно с false.
//
// Внимание: не оставляйте true — иначе пара будет стираться при каждой
// перезагрузке, и устройство будет пропадать из «Дома» после каждого перезапуска.
static const bool ERASE_PAIRING_ON_BOOT = false;

// --- Режим поиска адресов термостатов ---------------------------------------
// true → плата примерно раз в 30 секунд выводит в веб-журнал (http://<адрес>/status)
// полный список регистров всех адресов шины. Так выясняются адреса термостатов для
// массива ZONES ниже: ищите строки вида "dump 0x1A2B3C4D: ...". В обычной работе
// держите false.
static const bool DUMP_ENABLED = false;

// --- Зоны: адрес термостата → имя комнаты -----------------------------------
// Адреса выясняются через DUMP_ENABLED (см. выше) и у каждой системы свои.
// Имена задавайте латиницей: HomeSpan строит из них идентификаторы; переименовать
// на любой язык можно позже в приложении «Дом».
// Зоны можно добавлять и убирать, но существующие держите в ТОМ ЖЕ порядке —
// приложение «Дом» кеширует привязку по позиции, и сдвиг её ломает (см. NOTES).
struct ZoneConfig {
  uint32_t address;
  const char *name;
};

static const ZoneConfig ZONES[] = {
    {0xAABBCC01, "Living"},
    {0xAABBCC02, "Bedroom"},
    {0xAABBCC03, "Study"},
    {0xAABBCC04, "Bathroom1"},  // санузлы часто исключены из охлаждения (см. NOTES)
    {0xAABBCC05, "Bathroom2"},
};

static const size_t ZONE_COUNT = sizeof(ZONES) / sizeof(ZONES[0]);
